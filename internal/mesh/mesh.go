package mesh

import (
	"fmt"
	"os"
	"os/exec"
	"slices"
	"strings"

	"github.com/sfmunoz/i12e/internal/cmdutil"
	"github.com/sfmunoz/i12e/internal/mesh/node"
	"github.com/sfmunoz/logit"
)

var log = logit.Logit().WithLevel(logit.LevelInfo)

func getNodeLocal() (*node.Node, error) {
	nodeLocal, err := node.NewNode(node.WithLocal())
	if err != nil {
		return nil, err
	}
	return nodeLocal, nil
}

func getNodeList(remBase string) ([]*node.Node, error) {
	cmd := exec.Command("rclone", "lsf", "-R", "--files-only", remBase)
	bo, be, err := cmdutil.RunSimple(cmd)
	if err != nil {
		return nil, fmt.Errorf("'rclone lsf' failed': %s (stdout=%s, stderr=%s)", err, bo.String(), be.String())
	}
	entries := strings.Split(strings.TrimSpace(bo.String()), "\n")
	slices.Sort(entries)
	slices.Reverse(entries)
	nodeList := make([]*node.Node, 0)
	for _, entry := range entries {
		n, err := node.NewNode(node.WithRemote(entry))
		if err != nil {
			log.Error("'node.NewNode()' failed", "err", err, "entry", entry)
			continue
		}
		nodeList = append(nodeList, n)
	}
	return nodeList, nil
}

func filterNodeList(nodeList []*node.Node) ([]*node.Node, error) {
	nodeListRet := make([]*node.Node, 0)
	nodeBlock := make([]*node.Node, 0)
	for _, n := range nodeList {
		nbLen := len(nodeBlock)
		if nbLen < 1 || n.GetNodeName() == nodeBlock[nbLen-1].GetNodeName() {
			nodeBlock = append(nodeBlock, n)
			continue
		}
		if nbLen < 2 || nodeBlock[0].GetWgKey().GetPrivKey().Hex() !=
			nodeBlock[1].GetWgKey().GetPrivKey().Hex() {
			// ignore blocks with few (<2) or not repeated leading elements (i.e. no locked)
			nodeBlock = make([]*node.Node, 0)
			continue
		}
		nodeListRet = append(nodeListRet, nodeBlock[0])
		nodeBlock = make([]*node.Node, 0)
	}
	return nodeListRet, nil
}

func ifacePeersConfig(nodeList []*node.Node, nodeLocal *node.Node) error {
	nodeIdLocal := nodeLocal.GetNodeId()
	for _, n := range nodeList {
		if n.GetNodeId() == nodeIdLocal {
			log.Info("skipping local node", "node", n)
			continue
		}
		cmd := exec.Command(
			"wg", "set", node.GetNodeInterface(),
			"peer", n.GetWgKey().GetPubKey().B64(),
			"endpoint", n.GetWgEndpoint().String(),
			"allowed-ips", fmt.Sprintf("%s/32", n.GetNodeIP()),
		)
		bo, be, err := cmdutil.RunSimple(cmd)
		if err != nil {
			return fmt.Errorf("'wg set' failed': %s (stdout=%s, stderr=%s)", err, bo.String(), be.String())
		}
	}
	return nil
}

func etcHostsUpdate(nodeList []*node.Node) error {
	// Flatcar's default
	lines := []string{
		"#",
		"# autogenerated by i12e - do not edit",
		"#",
		"",
		"127.0.0.1 localhost",
		"::1 localhost",
	}
	for _, n := range nodeList {
		lines = append(lines, fmt.Sprintf("%s %s", n.GetNodeIP(), n.GetNodeName()))
	}
	lines = append(lines, "") // NL to the end
	buf := strings.Join(lines, "\n")
	return os.WriteFile("/etc/hosts", []byte(buf), 0644)
}

func Run(remBase string) error {
	nodeLocal, err := getNodeLocal()
	if err != nil {
		return err
	}
	if err := nodeLocal.PushToRemote(remBase); err != nil {
		return err
	}
	if err := nodeLocal.PurgeFromRemote(remBase); err != nil {
		return err
	}
	nodeListRaw, err := getNodeList(remBase)
	if err != nil {
		return err
	}
	nodeList, err := filterNodeList(nodeListRaw)
	if err != nil {
		return err
	}
	if err := nodeLocal.HostnameConfig(); err != nil {
		return err
	}
	if err := nodeLocal.IfaceLocalConfig(); err != nil {
		return err
	}
	if err := ifacePeersConfig(nodeList, nodeLocal); err != nil {
		return err
	}
	if err := etcHostsUpdate(nodeList); err != nil {
		return err
	}
	return nil
}
