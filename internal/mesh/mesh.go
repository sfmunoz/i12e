package mesh

import (
	"fmt"
	"os"
	"os/exec"
	"slices"
	"strings"

	"github.com/sfmunoz/i12e/internal/cmdutil"
	"github.com/sfmunoz/i12e/internal/mesh/node"
	"github.com/sfmunoz/logit"
)

var log = logit.Logit().WithLevel(logit.LevelInfo)

const remMeshBase = "rem:mesh" // FIXME unhardcode this

func getNodeList(remBase string) ([]*node.Node, error) {
	cmd := exec.Command("rclone", "lsf", "-R", "--files-only", remBase)
	bo, be, err := cmdutil.RunSimple(cmd)
	if err != nil {
		return nil, fmt.Errorf("'rclone lsf' failed': %s (stdout=%s, stderr=%s)", err, bo.String(), be.String())
	}
	entries := strings.Split(strings.TrimSpace(bo.String()), "\n")
	slices.Sort(entries)
	slices.Reverse(entries)
	nodeList := make([]*node.Node, 0)
	nodeNameLast := ""
	for _, entry := range entries {
		n, err := node.NewNode(node.WithRemote(entry))
		if err != nil {
			log.Error("'getNodeRemote()' failed", "err", err, "entry", entry)
			continue
		}
		nodeName := n.GetNodeName()
		if nodeName == nodeNameLast {
			continue
		}
		nodeNameLast = nodeName
		nodeList = append(nodeList, n)
	}
	return nodeList, nil
}

type Mesh struct {
	remBase  string
	nodeList []*node.Node
}

func (m *Mesh) procNodeList(nodeLocal *node.Node) error {
	nodeIdLocal := nodeLocal.GetNodeId()
	for i, n := range m.nodeList {
		if n.GetNodeId() != nodeIdLocal {
			continue
		}
		m.nodeList[i] = nodeLocal
		return nil
	}
	if err := nodeLocal.PushToRemote(m.remBase); err != nil {
		return fmt.Errorf("procNodeList(): couldn't find nodeLocal in nodeList but PushToRemote() failed: %q", err)
	}
	m.nodeList = append(m.nodeList, nodeLocal)
	return nil
}

func (m *Mesh) ifacePeersConfig() error {
	for _, n := range m.nodeList {
		if n.GetLocal() {
			log.Info("skipping local node", "node", n)
			continue
		}
		cmd := exec.Command(
			"wg", "set", node.GetNodeInterface(),
			"peer", n.GetWgKey().GetPubKey().B64(),
			"endpoint", n.GetWgEndpoint().String(),
			"allowed-ips", fmt.Sprintf("%s/32", n.GetNodeIP()),
		)
		bo, be, err := cmdutil.RunSimple(cmd)
		if err != nil {
			return fmt.Errorf("'wg set' failed': %s (stdout=%s, stderr=%s)", err, bo.String(), be.String())
		}
	}
	return nil
}

func (m *Mesh) etcHostsUpdate() error {
	// Flatcar's default
	lines := []string{
		"#",
		"# autogenerated by i12e - do not edit",
		"#",
		"",
		"127.0.0.1 localhost",
		"::1 localhost",
	}
	for _, n := range m.nodeList {
		lines = append(lines, fmt.Sprintf("%s %s", n.GetNodeIP(), n.GetNodeName()))
	}
	lines = append(lines, "") // NL to the end
	buf := strings.Join(lines, "\n")
	return os.WriteFile("/etc/hosts", []byte(buf), 0644)
}

func (m *Mesh) run() error {
	nodeLocal, err := node.NewNode(node.WithLocal()) // XXX nodeList is updated with nodeLocal
	if err != nil {
		return err
	}
	if err := m.procNodeList(nodeLocal); err != nil {
		return err
	}
	if err := nodeLocal.HostnameConfig(); err != nil {
		return err
	}
	if err := nodeLocal.IfaceLocalConfig(); err != nil {
		return err
	}
	if err := m.ifacePeersConfig(); err != nil {
		return err
	}
	if err := m.etcHostsUpdate(); err != nil {
		return err
	}
	return nil
}

func newMesh(remBase string) (*Mesh, error) {
	nodeList, err := getNodeList(remBase)
	if err != nil {
		return nil, err
	}
	return &Mesh{remBase, nodeList}, nil
}

func Run() error {
	mesh, err := newMesh(remMeshBase)
	if err != nil {
		return err
	}
	return mesh.run()
}
